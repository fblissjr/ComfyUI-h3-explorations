_INDEX_ENTRY_RE = re.compile(
    r"`(?P<path>[A-Za-z0-9_./-]+\.py)::(?P<sym>[A-Za-z0-9_.]+)`\s*\(`L(?P<start>\d+)-L(?P<end>\d+)`,\s*`#(?P<digest>[0-9a-f]{8})`\)"
)
_SUPPORT_LINE_RE = re.compile(r"^- \*\*`(?P<path>[A-Za-z0-9_./-]+\.py)`\*\*")
_SUPPORT_SYM_RE = re.compile(
    r"`(?P<sym>[A-Za-z0-9_.]+)`\s*\(`L(?P<start>\d+)-L(?P<end>\d+)`,\s*`#(?P<digest>[0-9a-f]{8})`\)"
)


def read_recorded_digests(md_text: str) -> dict[tuple[str, str], tuple[int, int, str]]:
    """Parse `(path, symbol) -> (start, end, digest)` out of `CODE_MAP_INDEX.md`."""
    recorded: dict[tuple[str, str], tuple[int, int, str]] = {}
    current_support_path: str | None = None
    for line in md_text.splitlines():
        for m in _INDEX_ENTRY_RE.finditer(line):
            recorded[(m.group("path"), m.group("sym"))] = (
                int(m.group("start")),
                int(m.group("end")),
                m.group("digest"),
            )
        sm = _SUPPORT_LINE_RE.match(line)
        if sm:
            current_support_path = sm.group("path")
        elif not line.startswith("  "):
            current_support_path = None
        if current_support_path is not None:
            for sym_m in _SUPPORT_SYM_RE.finditer(line):
                recorded[(current_support_path, sym_m.group("sym"))] = (
                    int(sym_m.group("start")),
                    int(sym_m.group("end")),
                    sym_m.group("digest"),
                )
    return recorded


_SYM_REF_RE = re.compile(r"`(?P<path>[A-Za-z0-9_./-]+\.py)::(?P<sym>[A-Za-z0-9_.]+)`")


def scan_narrative_sections(md_path: Path) -> list[tuple[str, int, list[tuple[str, str]]]]:
    """Return `[(heading, line_no, [(path, symbol), ...])]` for a narrative code-map doc."""
    if not md_path.is_file():
        return []
    sections: list[tuple[str, int, list[tuple[str, str]]]] = []
    current_heading = md_path.name
    current_line = 1
    current_syms: list[tuple[str, str]] = []
    for idx, line in enumerate(md_path.read_text(encoding="utf-8").splitlines(), start=1):
        if line.startswith("## ") or line.startswith("### "):
            if current_syms:
                sections.append((current_heading, current_line, current_syms))
            current_heading = line.strip()
            current_line = idx
            current_syms = []
        for m in _SYM_REF_RE.finditer(line):
            pair = (m.group("path"), m.group("sym"))
            if pair not in current_syms:
                current_syms.append(pair)
    if current_syms:
        sections.append((current_heading, current_line, current_syms))
    return sections


def compute_drift() -> tuple[list[str], list[str]]:
    """Return `(symbol_drift_lines, narrative_section_lines)` comparing disk vs `CODE_MAP_INDEX.md`."""
    if not INDEX_MD.is_file():
        return ([f"MISSING {INDEX_MD.relative_to(REPO)} (run --write first)"], [])
    recorded = read_recorded_digests(INDEX_MD.read_text(encoding="utf-8"))
    live_cache: dict[str, dict[str, tuple[int, int, str]]] = {}

    drifted_syms: dict[tuple[str, str], str] = {}
    for (rel_path, sym), (old_s, old_e, old_digest) in recorded.items():
        if rel_path not in live_cache:
            _, live_cache[rel_path] = parse_file_symbols(rel_path)
        live_syms = live_cache[rel_path]
        if sym not in live_syms:
            drifted_syms[(rel_path, sym)] = f"DELETED `{rel_path}::{sym}` (was L{old_s}-L{old_e})"
            continue
        new_s, new_e, new_digest = live_syms[sym]
        if new_digest != old_digest:
            drifted_syms[(rel_path, sym)] = (
                f"MODIFIED `{rel_path}::{sym}`: AST #{old_digest} -> #{new_digest} "
                f"(read_file StartLine={new_s}, EndLine={new_e})"
            )

    affected_sections: list[str] = []
    for doc in (STAGES_MD, CONTRACTS_MD, PLAN_MD):
        rel_doc = doc.relative_to(REPO)
        for heading, line_no, syms in scan_narrative_sections(doc):
            hits = [f"`{p}::{s}`" for (p, s) in syms if (p, s) in drifted_syms]
            if hits:
                affected_sections.append(
                    f"{rel_doc}:{line_no} ({heading}) -> touches {', '.join(hits)}"
                )
    return (list(drifted_syms.values()), affected_sections)


def check_all() -> int:
    """Run all staleness, symbol-existence, size, line-length, and path-privacy checks."""
    errs: list[str] = []
    expected = generate_index_markdown()
    if not INDEX_MD.is_file():
        errs.append(f"{INDEX_MD.relative_to(REPO)} does not exist (run `bench/masked_code_map.py --write`)")
    else:
        actual = INDEX_MD.read_text(encoding="utf-8")
        if actual != expected:
            errs.append(
                f"{INDEX_MD.relative_to(REPO)} is out of date with live AST extraction "
                "(run `bench/masked_code_map.py --write`)"
            )

    live_cache: dict[str, dict[str, tuple[int, int, str]]] = {}
    home_re = re.compile(r"/(?:home|Users)/[A-Za-z0-9_.-]+")

    for doc in CODE_MAP_DOCS:
        rel_doc = doc.relative_to(REPO)
        if not doc.is_file():
            errs.append(f"missing code-map document: {rel_doc}")
            continue
        raw = doc.read_bytes()
        if len(raw) > MAX_FILE_BYTES:
            errs.append(
                f"{rel_doc} is {len(raw):,} bytes > MAX_FILE_BYTES ({MAX_FILE_BYTES:,}); "
                "must fit in a single `read_file` call (< 46,080 bytes)"
            )
        text = raw.decode("utf-8")
        for line_no, line in enumerate(text.splitlines(), start=1):
            if len(line) > MAX_LINE_CHARS:
                errs.append(
                    f"{rel_doc}:{line_no} is {len(line)} chars > MAX_LINE_CHARS ({MAX_LINE_CHARS}); "
                    "break long table rows into vertical bullet blocks so `edit_file` never stalls"
                )
            if home_re.search(line):
                errs.append(
                    f"{rel_doc}:{line_no} contains a home-directory path; "
                    "use repo-relative paths or $H3_OUTPUT_DIR / $H3_INPUT_DIR"
                )
        for m in _SYM_REF_RE.finditer(text):
            p, s = m.group("path"), m.group("sym")
            full = REPO / p
            if not full.is_file():
                errs.append(f"{rel_doc} cites `{p}::{s}`, but `{p}` is not on disk")
                continue
            if p not in live_cache:
                _, live_cache[p] = parse_file_symbols(p)
            if s not in live_cache[p]:
                errs.append(f"{rel_doc} cites `{p}::{s}`, which does not exist in `{p}`'s AST")

    if errs:
        for e in errs:
            print(f"  FAIL  {e}")
        return 1

    print(f"  ok    {INDEX_MD.relative_to(REPO)} matches live AST across {len(CORE_FILES) + len(SUPPORT_FILES)} masked-lane files")
    for doc in CODE_MAP_DOCS:
        raw = doc.read_bytes()
        lines = raw.decode("utf-8").splitlines()
        max_l = max((len(l) for l in lines), default=0)
        print(f"  ok    {doc.relative_to(REPO)}: {len(raw):,} bytes, {len(lines)} lines, max line {max_l} chars")
    return 0


def query_symbols(query: str) -> int:
    """Print live `StartLine-EndLine` coordinates for any symbol or file matching `query`."""
    q = query.lower()
    all_paths = [p for _, p, _ in CORE_FILES] + [p for p, _ in SUPPORT_FILES]
    hits = 0
    for rel_path in all_paths:
        total_lines, symbols = parse_file_symbols(rel_path)
        file_match = q in rel_path.lower()
        for sym, (start, end, digest) in symbols.items():
            if file_match or q in sym.lower():
                print(f"{rel_path}::{sym}  L{start}-L{end}  (#{digest}, file {total_lines} lines)")
                hits += 1
    if hits == 0:
        print(f"no symbol or file matching {query!r}")
        return 1
    return 0


def query_deps(target: str | None) -> int:
    """Print bidirectional dependency chain (downstream imports/dynamic and upstream callers) for `target` or all files."""
    dep_graph = compute_dependency_graph()
    q = (target or "").lower()
    hits = 0
    for rel_path, edges in dep_graph.items():
        if q and q not in rel_path.lower():
            continue
        if not q and not any(edges.values()):
            continue
        hits += 1
        print(f"=== {rel_path} ===")
        if edges["imports"]:
            print(f"  imports ({len(edges['imports'])}):      " + ", ".join(edges["imports"]))
        if edges["dynamic"]:
            print(f"  dynamic/cli ({len(edges['dynamic'])}):  " + ", ".join(edges["dynamic"]))
        if edges["imported_by"]:
            print(f"  imported_by ({len(edges['imported_by'])}):  " + ", ".join(edges["imported_by"]))
        if edges["dynamic_by"]:
            print(f"  called_by ({len(edges['dynamic_by'])}):    " + ", ".join(edges["dynamic_by"]))
    if hits == 0:
        print(f"no masked-lane file matching {target!r}")
        return 1
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--write", action="store_true", help="Write docs/masked_v2v/CODE_MAP_INDEX.md from live AST.")
    ap.add_argument("--check", action="store_true", help="Verify index freshness, symbol resolution, file size, line length, and path privacy.")
    ap.add_argument("--drift", action="store_true", help="Report AST function changes since CODE_MAP_INDEX.md was written and which narrative stages they affect.")
    ap.add_argument("--deps", nargs="?", const="", default=None, help="Print bidirectional module dependency graph (optionally filtered by file substring).")
    ap.add_argument("query", nargs="?", help="Optional function or filename substring to look up.")
    args = ap.parse_args()

    if args.write:
        text = generate_index_markdown()
        INDEX_MD.parent.mkdir(parents=True, exist_ok=True)
        INDEX_MD.write_text(text, encoding="utf-8")
        print(f"wrote {INDEX_MD.relative_to(REPO)} ({len(text.encode('utf-8')):,} bytes, {len(text.splitlines())} lines)")

    if args.deps is not None:
        return query_deps(args.deps or args.query)

    if args.drift:
        sym_lines, sec_lines = compute_drift()
        if not sym_lines:
            print("0 drifted symbols; all narrative stage/contract blocks in docs/masked_v2v/ are current.")
        else:
            print(f"{len(sym_lines)} symbol(s) changed AST body since {INDEX_MD.relative_to(REPO)} was written:")
            for line in sym_lines:
                print(f"  - {line}")
            if sec_lines:
                print(f"\n{len(sec_lines)} narrative section(s) to review:")
                for line in sec_lines:
                    print(f"  - {line}")
        if not args.check:
            return 0

    if args.check:
        return check_all()

    if args.query:
        return query_symbols(args.query)

    if not (args.write or args.check or args.drift):
        ap.print_help()
    return 0


if __name__ == "__main__":
    sys.exit(main())
