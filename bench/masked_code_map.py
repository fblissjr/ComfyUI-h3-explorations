#!/usr/bin/env python3
"""Generate and check the masked-lane AST jump index and stage-symbol drift map.

    <python> bench/masked_code_map.py --write        # rewrite docs/masked_v2v/CODE_MAP_INDEX.md
    <python> bench/masked_code_map.py --check        # exit 1 if stale, oversized, or drifted
    <python> bench/masked_code_map.py --drift        # report functions & narrative stages changed
    <python> bench/masked_code_map.py <query>        # print live StartLine-EndLine for a symbol/file

Why this exists:
Five Gemini/AGY sessions in a row stalled on a 163 KB single-file code map whose
3,500-char table rows exceeded `read_file`'s 46,080-byte per-call cap and forced
`edit_file` to stream 10,000+ output tokens per edit, while hand-typed line
numbers drifted on every commit.

This tool splits mechanical line-number / `cannot_see` indexing from narrative
stage documentation:
1. It parses the declared git-tracked masked-lane Python modules with `ast` (no
   torch, no ComfyUI, no GPU, <0.1s) and writes `docs/masked_v2v/CODE_MAP_INDEX.md`
   with exact `StartLine-EndLine` coordinates and an 8-char AST body digest per
   symbol, plus live-extracted `cannot_see` constants.
2. It cross-checks every `- **Symbols**:` citation in `docs/masked_v2v/code_map_stages.md`
   and `docs/masked_v2v/code_map_contracts.md` against the live AST, and in
   `--drift` mode reports the exact `### Stage` / `### Section` blocks whose
   underlying Python function bodies changed since `CODE_MAP_INDEX.md` was last
   written.
3. In `--check` mode it enforces that `CODE_MAP_INDEX.md` is current, every
   symbol resolves, every code-map `.md` file stays under `MAX_FILE_BYTES`
   (35,000 bytes, well inside `read_file`'s 46,080-byte cap) and `MAX_LINE_CHARS`
   (400 chars, preventing single-line table stalls), and no code-map file
   contains a machine-specific `/home/` or `/Users/` path.
"""

