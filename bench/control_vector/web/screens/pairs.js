// Building from prompt pairs: in place on one prompt (`from-prompt`), or from a pair file (`build`).
//
// An edit to compiled pairs is made in the pair file, never in the page's memory: "Edit as a pair
// file" moves them into the editor, the editor saves a .toml with `from-md`, and `build` reads the
// .toml. So what was built is always something the command line can build again.

import { studio, onListing, apiPost, h, setStatus } from '../api.js';
import { buildForm, methodCard, resultPanel } from '../form.js';
import { pairsView } from '../readout.js';

export function mount(root, nav) {
  // --- the pair file editor -----------------------------------------------------------------
  const editor = h('textarea', { class: 'mono large-editor', spellcheck: 'false',
    placeholder: '#### Pair 1\n##### Prompt A (Baseline)\n...\n\n##### Prompt B (Steered)\n...' });
  const fileList = h('datalist', { id: 'pair-file-list' });
  const fileInput = h('input', { type: 'text', class: 'mono', list: 'pair-file-list', placeholder: 'a pair file in the library' });
  const fillFiles = () => fileList.replaceChildren(...studio.tomlFiles.map((t) => h('option', { value: t.stem })));
  fillFiles();
  onListing(fillFiles);
  const saveForm = buildForm('from-md', { exclude: ['md_path'] });
  const editorPanel = resultPanel();
  const buildCard = methodCard('build', { title: 'Build from the pair file', runLabel: 'Build' });

  const step = (btn, text, fn) => async () => {
    btn.disabled = true;
    editorPanel.busy(text);
    setStatus(text, 'busy');
    try {
      await fn();
      setStatus('Ready', 'ok');
    } catch (err) {
      editorPanel.error(err);
      setStatus('Refused', 'err');
    } finally {
      btn.disabled = false;
    }
  };

  async function loadFile(stem) {
    const res = await apiPost('/api/load-toml', { file: stem });
    editor.value = res.markdown;
    saveForm.set('name', res.name);
    buildCard.form.set('source', res.path);
    editorPanel.note(`Loaded ${res.file}: ${res.n_pairs} pair(s), ${res.n_holds} hold(s), mode ${res.mode}.`);
  }
  const loadBtn = h('button', { type: 'button', class: 'btn' }, 'Load');
  loadBtn.addEventListener('click', step(loadBtn, 'Loading...', () => loadFile(fileInput.value.trim())));

  const checkBtn = h('button', { type: 'button', class: 'btn' }, 'Check the pairs');
  checkBtn.addEventListener('click', step(checkBtn, 'Checking...', async () => {
    const res = await apiPost('/api/preview', { text: editor.value, name: saveForm.get('name') || '' });
    const warnings = res.lint_warnings || [];
    editorPanel.note(
      `${res.n_pairs} pair(s), ${res.n_holds} hold(s), mode ${res.mode}. `,
      warnings.length ? h('ul', {}, warnings.map((w) => h('li', {}, typeof w === 'string' ? w : JSON.stringify(w)))) : 'No warnings.');
  }));

  const saveBtn = h('button', { type: 'button', class: 'btn btn-primary' }, 'Save the pair file');
  saveBtn.addEventListener('click', step(saveBtn, 'Saving...', async () => {
    const res = await apiPost('/api/save-toml', { text: editor.value, args: saveForm.values() });
    buildCard.form.set('source', res.toml_path);
    editorPanel.show(res);
  }));

  // --- in place on one prompt ---------------------------------------------------------------
  const inPlace = methodCard('from-prompt', {
    title: 'In place on a prompt',
    runLabel: 'Build',
    actions: [{
      label: 'Preview the pairs',
      async run(values, panel) {
        const res = await apiPost('/api/compile', { args: values });
        const edit = h('button', { type: 'button', class: 'btn btn-sm' }, 'Edit as a pair file');
        edit.addEventListener('click', () => {
          editor.value = res.markdown;
          saveForm.set('name', res.name);
          editor.scrollIntoView({ behavior: 'smooth', block: 'center' });
        });
        panel.note(pairsView(res), h('div', { class: 'btn-row' }, edit));
      },
    }],
  });

  // --- pairs from a local LLM ---------------------------------------------------------------
  const llmForm = buildForm('generate-pairs', {
    preset: { llm_provider: studio.init.default_llm_provider, llm_model: studio.init.default_llm_model },
  });
  const llmPanel = resultPanel();
  const llmBtn = h('button', { type: 'button', class: 'btn' }, 'Generate into the editor');
  llmBtn.addEventListener('click', async () => {
    llmBtn.disabled = true;
    llmPanel.busy('Generating pairs...');
    setStatus('Generating pairs...', 'busy');
    try {
      const res = await apiPost('/api/generate-pairs-llm', { args: llmForm.values() });
      editor.value = res.markdown || '';
      llmPanel.note(`Generated by ${res.provider} in ${res.elapsed_s}s. The pairs are in the editor above.`);
      setStatus('Ready', 'ok');
    } catch (err) {
      llmPanel.error(err);
      setStatus('Refused', 'err');
    } finally {
      llmBtn.disabled = false;
    }
  });
  const copyBtn = h('button', { type: 'button', class: 'btn btn-sm' }, 'Copy the system prompt');
  copyBtn.addEventListener('click', async () => {
    await navigator.clipboard.writeText(studio.init.system_prompt || '');
    copyBtn.textContent = 'Copied';
  });

  root.append(
    h('div', { class: 'screen-header' },
      h('h2', { class: 'screen-title' }, 'Pairs'),
      h('p', { class: 'screen-desc' }, 'A vector from prompt pairs that differ in one thing: one prompt changed in place, or a file of pairs.')),
    inPlace.el,
    h('section', { class: 'card' },
      h('div', { class: 'card-header' }, h('h3', { class: 'card-title' }, 'Pair file'),
        h('code', { class: 'method-tag' }, 'from-md')),
      h('p', { class: 'field-hint' }, 'Load a pair file, or write pairs as Markdown. Saving runs from-md on the text below.'),
      h('div', { class: 'btn-row' }, fileInput, fileList, loadBtn),
      editor,
      saveForm.el,
      h('div', { class: 'btn-row' }, checkBtn, saveBtn),
      editorPanel.el),
    buildCard.el,
    h('section', { class: 'card' },
      h('div', { class: 'card-header' }, h('h3', { class: 'card-title' }, 'Pairs from a local LLM'),
        h('code', { class: 'method-tag' }, 'generate-pairs')),
      h('p', { class: 'field-hint' }, studio.methods['generate-pairs'].help),
      llmForm.el,
      h('div', { class: 'btn-row' }, llmBtn, copyBtn),
      llmPanel.el));

  nav.on('pairs', (params) => {
    if (params && params.pairFile) {
      fileInput.value = params.pairFile;
      loadBtn.click();
    }
  });
}
