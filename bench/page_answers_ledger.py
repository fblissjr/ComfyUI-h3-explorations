#!/usr/bin/env python3
"""Every line the owner saved on the local page, beside the record that carries it, and the lines no record cites yet.

    <python> bench/page_answers_ledger.py --answers data/<stem>/owner_answers.jsonl --cast data/<stem>/cast/cast.jsonl \\
        --verdicts data/<stem>/verdicts/verdicts.jsonl --shots data/<stem>/shots.json --plan data/<stem>/plan.json \\
        [--who owner] [--out data/<stem>/verdicts/answers_ledger.md]

**What it buys.** The owner asked (2026-10-12) to be sure that everything they saved on the page (who is who, the
clip verdicts, their words on shots and rows) is used and reachable. Four records each take some of those lines
and cite them by line number: the cast file (`bench/page_answers_to_cast.py`, "lines a-b" in `by`), the verdicts
record (`bench/page_answers_to_verdicts.py`, `source: answers.jsonl:N`), the shots record (`notes` with
"answers.jsonl line N") and the plan (a departure's `note` with "line N"). Nothing lays the four side by side, so
a line that reached none of them is invisible. This prints that ledger and writes it as one Markdown file: a row a
line of the owner's, with its row id, frames, what was clicked or typed, and which record cites it; then the lines
no record cites, whole, grouped by the page's row, for a session to place or to say why not.

**What it does not do.** It writes nothing into any record and judges no line. A line a record holds without
citing its number is counted as uncited here: the citation is the thing it checks.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

LINE_RE = re.compile(r"answers\.jsonl:(\d+)")
RANGE_RE = re.compile(r"lines? (\d+)(?:\s*-\s*(\d+))?")


def cited(text: str, into: set[int]) -> None:
    """Every answers.jsonl line number a record's text names, as `answers.jsonl:N`, `line N` or `lines a-b`."""
    for m in LINE_RE.finditer(text):
        into.add(int(m.group(1)))
    for m in RANGE_RE.finditer(text):
        a, b = int(m.group(1)), int(m.group(2) or m.group(1))
        if b >= a and b - a < 10000:
            into.update(range(a, b + 1))


def citations(cast: list[dict], verdicts: list[dict], shots: dict | None, plan: dict | None) -> dict[str, set[int]]:
    out: dict[str, set[int]] = {"cast": set(), "verdicts": set(), "shots": set(), "plan": set()}
    for c in cast:
        cited(str(c.get("by", "")), out["cast"])
    for v in verdicts:
        cited(str(v.get("source", "")), out["verdicts"])
    if shots:
        for s in shots.get("shots", []):
            cited(str(s.get("note", "")), out["shots"])
            for w in (s.get("who") or {}).values():
                cited(str(w.get("how", "")) + " " + str(w.get("by", "")), out["shots"])
    if plan:
        for d in plan.get("departures", []):
            cited(str(d.get("note", "")), out["plan"])
        for v in (plan.get("subjects") or {}).values():
            cited(str(v.get("by", "")), out["plan"])
    return out


def ledger(lines: list[dict], who: str, cites: dict[str, set[int]]) -> dict:
    rows, uncited = [], []
    for n, l in enumerate(lines, 1):
        if l.get("who") != who:
            continue
        where = [k for k, s in cites.items() if n in s]
        said = l.get("words") if l.get("what") == "words" else l.get("chosen")
        row = {"line": n, "row": str(l.get("row", "")), "what": str(l.get("what", "")), "frame": l.get("source_frame"),
               "frames": l.get("frames"), "said": said, "at": str(l.get("at", ""))[:16], "cited_by": where}
        rows.append(row)
        if not where:
            uncited.append(row)
    return {"who": who, "lines": len(lines), "owners": len(rows), "cited": len(rows) - len(uncited), "uncited": uncited, "rows": rows}


def markdown(led: dict, answers: str) -> str:
    out = [f"# The owner's lines on the local page, and where each went", "",
           f"From `{answers}`: {led['lines']} lines, {led['owners']} by `{led['who']}`; {led['cited']} cited by a record by line number, "
           f"{len(led['uncited'])} cited by none. A record citing a line is the only thing counted; a line a record holds "
           f"without its number reads as uncited here. Generated by `bench/page_answers_ledger.py`; nothing here is a verdict.", ""]
    by = Counter(tuple(r["cited_by"]) for r in led["rows"])
    out += ["## Where the lines went", "", "| cited by | lines |", "|---|---|"]
    for k, v in sorted(by.items(), key=lambda kv: -kv[1]):
        out.append(f"| {', '.join(k) or 'no record'} | {v} |")
    out += ["", "## Lines no record cites, whole, by the page's row", ""]
    groups: dict[str, list[dict]] = defaultdict(list)
    for r in led["uncited"]:
        groups[r["row"]].append(r)
    for row, rs in sorted(groups.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        out.append(f"### row `{row}` ({len(rs)})")
        out.append("")
        for r in rs:
            fr = f"frames {r['frames'][0]}-{r['frames'][1]}" if isinstance(r.get("frames"), list) and len(r["frames"]) == 2 else ""
            f1 = f"frame {r['frame']}" if r.get("frame") not in (None, "") else ""
            said = str(r["said"]) if r["said"] not in (None, "") else "(no words, no button)"
            out.append(f"- line {r['line']} ({r['what']}; {f1}{', ' if f1 and fr else ''}{fr}; {r['at']}): {said}")
        out.append("")
    out += ["## Every line", "", "| line | row | what | frame | frames | said | cited by |", "|---|---|---|---|---|---|---|"]
    for r in led["rows"]:
        said = str(r["said"]).replace("|", "\\|").replace("\n", " ") if r["said"] not in (None, "") else ""
        fr = f"{r['frames'][0]}-{r['frames'][1]}" if isinstance(r.get("frames"), list) and len(r["frames"]) == 2 else ""
        out.append(f"| {r['line']} | {r['row']} | {r['what']} | {r['frame'] if r['frame'] is not None else ''} | {fr} | {said[:160]} | {', '.join(r['cited_by'])} |")
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=(__doc__ or "").split("\n")[0])
    ap.add_argument("--answers", required=True)
    ap.add_argument("--cast", required=True)
    ap.add_argument("--verdicts", required=True)
    ap.add_argument("--shots")
    ap.add_argument("--plan")
    ap.add_argument("--who", default="owner", help="whose lines are laid out; the page's 'who' field")
    ap.add_argument("--out", help="the ledger as Markdown (a .json with the same stem goes beside it); printed only when left out")
    a = ap.parse_args()
    lines = [json.loads(t) for t in Path(a.answers).read_text().splitlines() if t.strip()]
    cast = [json.loads(t) for t in Path(a.cast).read_text().splitlines() if t.strip()]
    verdicts = [json.loads(t) for t in Path(a.verdicts).read_text().splitlines() if t.strip()]
    shots = json.load(open(a.shots)) if a.shots else None
    plan = json.load(open(a.plan)) if a.plan else None
    led = ledger(lines, a.who, citations(cast, verdicts, shots, plan))
    text = markdown(led, a.answers)
    if a.out:
        out = Path(a.out)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text)
        out.with_suffix(".json").write_text(json.dumps(led, indent=1, ensure_ascii=False))
        print(f"written: {out} and {out.with_suffix('.json').name}; {led['owners']} lines by {led['who']}, {led['cited']} cited, {len(led['uncited'])} uncited")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
